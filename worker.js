const BACKEND = 'https://pahl-backend-production.up.railway.app';

export default {
  async fetch(request, env, ctx) {
    const url = new URL(request.url);
    const path = url.pathname;

    if (path === '/' || path === '') return html(HOME_HTML);
    if (path === '/driver-register' || path === '/driver-register.html') return html(REGISTER_HTML);
    if (path === '/driver-application-submitted' || path === '/driver-application-submitted.html') return html(SUBMITTED_HTML);
    if (path === '/admin-drivers' || path === '/admin-drivers.html') return html(ADMIN_HTML);
    if (path === '/driver-login' || path === '/driver-login.html') return html(LOGIN_HTML);
    if (path === '/driver-dashboard' || path === '/driver-dashboard.html') return html(DASHBOARD_HTML);
    if (path === '/shop' || path === '/shop.html') return html(SHOP_HTML);
    if (path === '/admin-products' || path === '/admin-products.html') return html(ADMIN_PRODUCTS_HTML);
    if (path === '/admin-orders' || path === '/admin-orders.html') return html(ADMIN_ORDERS_HTML);
    if (path.startsWith('/product/')) return html(PRODUCT_HTML);
    if (path === '/checkout' || path === '/checkout.html') return html(CHECKOUT_HTML);
    if (path === '/checkout/success') return html(CHECKOUT_SUCCESS_HTML);
    if (path === '/checkout/failure') return html(CHECKOUT_FAILURE_HTML);
    if (path === '/checkout/cancel') return html(CHECKOUT_CANCEL_HTML);

    return new Response('Route not found', { status: 404 });
  }
};

function html(body) {
  return new Response(body, {
    headers: { 'Content-Type': 'text/html; charset=utf-8' }
  });
}

